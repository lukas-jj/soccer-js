const assert = require('node:assert/strict');
const C = require('../kernel/rogue/career.js');
const P = require('../kernel/rogue/players.js');
const { CONFIG } = require('../kernel/rogue/data.js');
const fresh = () => C.newRun('harbor', 123);
let s = fresh();
assert.equal(s.squad.length, 16);
assert.equal(s.division, 0);
assert.equal(new Set(s.lineup).size, 11);
assert.ok(s.squad.every(p => p.perks.length <= 1 && p.curses.length <= 1));
assert.deepEqual(fresh(), s, 'seeded creation');
let p = s.squad[0];
P.awardMinutes(s, p, 'GK', 90);
P.awardMinutes(s, p, 'DF', 30);
assert.equal(p.minutes.GK, 90);
assert.equal(p.minutes.DF, 30);
assert.ok(p.pending.length > 0);
const before = p.stats[p.pending[0][0].stat];
P.chooseUpgrade(p, 0);
assert.ok(p.stats[p.pending.length ? p.pending[0][0].stat : 'goalkeeping'] >= 1);
assert.throws(() => P.chooseUpgrade(p, 9));
s = fresh(); p = s.squad[0];
const xp = p.xp, passing = p.stats.passing;
C.activity(s, 'train', { type: 'passing' });
assert.equal(p.xp, xp, 'training never gives XP');
assert.ok(p.stats.passing > passing);
assert.equal(s.prepLeft, 2);
assert.throws(() => C.activity(s, 'train', { type: 'shooting' }));
assert.equal(s.prepLeft, 2, 'invalid action must not consume day');
C.activity(s, 'rest'); C.activity(s, 'rest');
assert.throws(() => C.activity(s, 'rest'));
s = fresh(); C.activity(s, 'shop');
const funds = s.money;
C.buy(s, 'spray'); assert.equal(s.money, funds - CONFIG.items.spray.price);
p = s.squad[0]; p.fatigue = 70; C.useItem(s, 'spray', p.id); assert.ok(p.fatigue < 70);
s.money = 0; assert.throws(() => C.buy(s, 'treatment')); assert.equal(s.money, 0);
s = fresh(); p = s.squad[0]; p.injury = { name: 'Sprain', days: 3, severity: 'moderate' };
C.activity(s, 'rest'); assert.equal(p.injury.days, 2);
C.activity(s, 'rest'); C.activity(s, 'rest'); assert.equal(p.injury, null);
s = fresh(); p = s.squad[0]; p.curses = ['party'];
P.trainPlayer(s, p, ['passing'], () => 0); assert.ok(p.fatigue >= 40, 'party curse triggers');
p.perks = ['engine']; const boosted = P.effectiveStats(s, p, 'MF', 'rainy');
p.perks = []; const plain = P.effectiveStats(s, p, 'MF', 'rainy'); assert.ok(boosted.stamina > plain.stamina);
s = fresh(); const rain = P.effectiveStats(s, s.squad[1], 'DF', 'rainy');
const fine = P.effectiveStats(s, s.squad[1], 'DF', 'fine'); assert.ok(rain.speed > fine.speed);
assert.deepEqual(C.decodeSave(C.encodeSave(s)), s);
assert.throws(() => C.decodeSave('{"version":999}'));
assert.throws(() => C.decodeSave('bad'));
s = fresh(); const slot = s.lineup[0]; C.assign(s, 1, slot); assert.equal(s.lineup[1], slot); assert.equal(new Set(s.lineup).size,11);
assert.throws(() => C.sell(s, s.lineup[0]));
for (let div = 0; div < 3; div++) {
 s = fresh(); s.division = div; s.table = [{id:s.clubId,points:99,gf:9,ga:0},{id:'rival',points:0,gf:0,ga:9}];
 C.endSeason(s); if(div<2) assert.equal(s.division,div+1); else assert.equal(s.phase,'victory');
}
s = fresh(); s.table = [{id:'rival',points:99,gf:9,ga:0},{id:s.clubId,points:0,gf:0,ga:9}]; C.endSeason(s); assert.equal(s.phase,'gameover');
s = fresh(); s.money=0; C.charge(s, 1, 'upkeep'); assert.equal(s.phase,'gameover');
console.info('Soccer Rogue career tests passed');
